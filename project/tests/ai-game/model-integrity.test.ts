import {describe,it,expect} from 'vitest';
import {mkdtemp,writeFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {verifyPinnedModel} from '../../server/analysis/model-integrity';
import {KataGoEngine} from '../../server/analysis/engine';

describe('generic internal network names require actual checkpoint identity',()=>{
 it('streams the file checksum and rejects corruption before engine launch',async()=>{
  const dir=await mkdtemp(join(tmpdir(),'go-extreme-integrity-')),path=join(dir,'model');
  // Independently known SHA-256 of ASCII abc; not generated by the function under test.
  const sha='ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad';
  try{await writeFile(path,'abc');await expect(verifyPinnedModel(path,sha)).resolves.toBeUndefined();await writeFile(path,'abd');await expect(verifyPinnedModel(path,sha)).rejects.toThrow('mismatch');await expect(verifyPinnedModel(path,'bad')).rejects.toThrow('checksum');await expect(verifyPinnedModel(path+'-missing',sha)).rejects.toThrow();}finally{await rm(dir,{recursive:true,force:true});}
 });
 it.each([true,false])('explicit transport fixture: internal-name handshake match=%s',async(match)=>{
  const engine=new KataGoEngine({executable:process.execPath,args:[fileURLToPath(new URL('../analysis/process-fixture.mjs',import.meta.url))],version:'1.18.1',model:'official-checkpoint-label',internalModelName:match?'test-model':'wrong-architecture',maxVisits:64,maxQueue:1,timeoutMs:500,startupTimeoutMs:500,restartDelayMs:10000});
  try{engine.start();for(let i=0;i<100;i++){if(engine.health().ready||engine.health().status==='restarting')break;await new Promise(r=>setTimeout(r,10));}expect(engine.health().ready).toBe(match);expect(engine.health().model).toBe('official-checkpoint-label');}finally{await engine.stop();}
 });
});
