import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
import {networkInterfaces} from 'node:os';
import {createOnlineServer} from './http';
import {fileRoomRepository} from './rooms';
const root=fileURLToPath(new URL('../',import.meta.url));
const port=Number(process.env.PORT??4190),host=process.env.HOST??'0.0.0.0';
if(!Number.isInteger(port)||port<1||port>65535)throw Error('PORT must be between 1 and 65535.');
const interfaces=networkInterfaces(),addresses=[...(interfaces.en0??[]),...(interfaces.eth0??[]),...Object.values(interfaces).flatMap(values=>values??[])];
const lan=host==='0.0.0.0'?addresses.find(item=>item.family==='IPv4'&&!item.internal&&/^(192\.168\.|10\.|172\.(1[6-9]|2\d|3[01])\.)/.test(item.address))?.address:null;
const publicApp=process.env.PUBLIC_APP_URL?new URL(process.env.PUBLIC_APP_URL):null;
if(publicApp&&(!['http:','https:'].includes(publicApp.protocol)||publicApp.username||publicApp.password))throw Error('PUBLIC_APP_URL must be a public HTTP(S) page URL without credentials.');
const shareUrl=publicApp?publicApp.href:process.env.PUBLIC_ORIGIN?new URL('/#/play/online',process.env.PUBLIC_ORIGIN).href:lan?`http://${lan}:${port}/#/play/online`:undefined;
const app=await createOnlineServer({distDir:resolve(root,'dist'),repository:fileRoomRepository(process.env.GO_CLUB_DATA_FILE??resolve(root,'runtime-data/rooms.json')),publicOrigin:process.env.PUBLIC_ORIGIN,shareUrl});
await app.listen(port,host);
console.log(`围棋社联机服务已启动：http://127.0.0.1:${port}/#/play/online`);
if(host==='0.0.0.0')for(const values of Object.values(networkInterfaces()))for(const item of values??[])if(item.family==='IPv4'&&!item.internal)console.log(`同一网络的候选地址：http://${item.address}:${port}/#/play/online`);
console.log('Ctrl+C 关闭服务。公网使用请配置 HTTPS 和 PUBLIC_ORIGIN；仅提供此电脑/局域网地址不代表已部署公网。');
let closing=false;const stop=async()=>{if(closing)return;closing=true;await app.close();process.exit(0);};process.on('SIGINT',stop);process.on('SIGTERM',stop);
